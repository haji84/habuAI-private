"""Synthetic-only GitHub Actions cache proof; no user data or inference.

This checks cross-run cache transport, NOT code-review quality or model output.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import cache as sha_cache

MOCK_PATH = "fixture/zero_findings.py"
MOCK_DIFF = "diff --git a/fixture/zero_findings.py b/fixture/zero_findings.py\n@@ -0,0 +1 @@\n+return 1\n"
MOCK_PROMPT = "Synthetic mock review; never a model inference.\n" + MOCK_DIFF
MOCK_MODEL = "synthetic-offline-zero-v1"
MOCK_MODEL_DIGEST = hashlib.sha256(b"fixture-not-a-real-model").hexdigest()


def prove(cache_dir: str) -> str:
    """Require that restored entries match complete byte-and-configuration IDs."""
    revision = sha_cache.reviewer_revision(Path(__file__), Path(sha_cache.__file__))
    segment_id = hashlib.sha256(MOCK_DIFF.encode("utf-8")).hexdigest()[:16]
    cache_key = sha_cache.fingerprint(
        path=MOCK_PATH, number=1, total=1, owned=MOCK_DIFF,
        prompt=MOCK_PROMPT, segment_id=segment_id,
        model=MOCK_MODEL, digest=MOCK_MODEL_DIGEST, revision=revision,
    )
    stored = sha_cache.VerifiedZeroCache(cache_dir)
    if stored.has(cache_key, segment_id):
        outcome = "RESTORED_MATCHING_ZERO_RECEIPT"
    else:
        # The response is intentionally a fixture, not generated by Qwen.
        receipt = json.loads(json.dumps({"segment_id": segment_id, "findings": []}))
        if receipt != {"segment_id": segment_id, "findings": []}:
            raise ValueError("Synthetic zero-finding receipt was not exact")
        stored.remember(cache_key, segment_id)
        outcome = "SYNTHETIC_ZERO_RECEIPT_SAVED"
    if not stored.has(cache_key, segment_id):
        raise AssertionError("Expected exact SHA cache receipt")
    for changes in (
        {"owned": MOCK_DIFF + "x"},
        {"prompt": MOCK_PROMPT + " x"},
        {"digest": hashlib.sha256(b"another-fake-model").hexdigest()},
        {"revision": hashlib.sha256(b"another-probe-version").hexdigest()},
    ):
        identity = {
            "path": MOCK_PATH, "number": 1, "total": 1,
            "owned": MOCK_DIFF, "prompt": MOCK_PROMPT,
            "segment_id": segment_id, "model": MOCK_MODEL,
            "digest": MOCK_MODEL_DIGEST, "revision": revision,
        }
        identity.update(changes)
        other = sha_cache.fingerprint(**identity)
        if stored.has(other, segment_id):
            raise AssertionError("Changed identity reused an old receipt")
    raw = (Path(cache_dir) / "index.json").read_text(encoding="utf-8")
    for forbidden in (MOCK_PATH, MOCK_DIFF, MOCK_PROMPT, "GPS", "latitude", "longitude"):
        if forbidden in raw:
            raise AssertionError("Non-hash data escaped into cache")
    if not set(json.loads(raw)) == {"version", "entries"}:
        raise AssertionError("Unexpected cache format")
    print(f"SYNTHETIC_PROBE: {outcome}", flush=True)
    print("SYNTHETIC_PROBE_IDENTITY_CHECK: PASS", flush=True)
    print("SYNTHETIC_PROBE_PRIVATE_DATA_CHECK: PASS", flush=True)
    print("SYNTHETIC_PROBE_IS_REAL_AI_REVIEW: NO", flush=True)
    return outcome


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cache-dir", required=True)
    args = parser.parse_args()
    prove(args.cache_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
